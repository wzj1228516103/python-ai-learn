"""
    企业知识库问答系统（LangChain 1.0）

    功能：
    - 文档批量导入
    - 智能分块
    - 向量检索
    - RAG 问答
    - 答案溯源
"""

from datetime import datetime
import json
import os

from dotenv import load_dotenv
from langchain.chat_models import init_chat_model
from langchain_community.document_loaders import DirectoryLoader, TextLoader
from langchain_community.vectorstores import FAISS
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnablePassthrough
from langchain_openai import OpenAIEmbeddings
from langchain_text_splitters import RecursiveCharacterTextSplitter


load_dotenv()

class KnowledgeBase:
    """企业知识库系统"""

    def __init__(
        self,
        docs_directory: str = "./knowledge_docs",
        index_directory: str = "./knowledge_index",
        embedding_model: str = "text-embedding-v4"
    ):
        self.docs_directory = docs_directory
        self.index_directory = index_directory

        # 初始化 Embedding
        print("初始化 Embedding模型...")
        self.embeddings = OpenAIEmbeddings(
            base_url= "https://dashscope.aliyuncs.com/compatible-mode/v1",
            api_key=os.getenv("OPENAI_API_KEY") or os.getenv("DASHSCOPE_API_KEY"),
            model="text-embedding-v4",
            # DashScope accepts text strings, not the token arrays generated by
            # LangChain's default context-length check.
            check_embedding_ctx_length=False,
        )

        print(" Embedding模型初始化完成！")

        # 文本分块器
        self.text_splitter = RecursiveCharacterTextSplitter(
            chunk_size=500,
            chunk_overlap=50,
            separators=["\n\n", "\n", "！", "。", "？", "；", "，", " ", ""]
        )

        # 向量数据库
        self.vectorstore = None

        # LLM
        self.model = init_chat_model(
            model="qwen-plus",
            model_provider="openai",
            base_url= "https://dashscope.aliyuncs.com/compatible-mode/v1",
            api_key=os.getenv("DASHSCOPE_API_KEY") or os.getenv("OPENAI_API_KEY"),
            temperature=0.0,
        )

        # 查询历史
        self.query_log = []

    def build_index(self):
        """构建索引"""
        print("开始构建索引...")

        # 1.加载文档
        print("\n 正在加载文档")
        loader = DirectoryLoader(
            self.docs_directory,
            glob="**/*.txt",
            loader_cls=TextLoader,
            loader_kwargs={"encoding": "utf-8"},
            show_progress=True
        )

        try:
            docs = loader.load()
            print(f"加载的文档数量：{len(docs)}")
        except Exception as e:
            print(f"加载文档时出错：{e}")
            return False

        if not docs:
            print("没有找到文档，请确保文档目录下有 .txt 文件")
            return False

        # 2.文本分块
        print("\n 正在分块文档")
        split_docs = self.text_splitter.split_documents(docs)
        print(f"分块完成，共生成 {len(split_docs)} 个块")

        # 3.创建向量数据库
        print("正在创建向量化并建立索引...")
        self.vectorstore = FAISS.from_documents(split_docs, self.embeddings)
        self.vectorstore.save_local(self.index_directory)
        print(f"索引已保存到 {self.index_directory}")

        return True

    def load_index(self):
        """加载已有索引"""
        print("正在加载索引...")
        try:
            self.vectorstore = FAISS.load_local(
                self.index_directory,
                self.embeddings,
                allow_dangerous_deserialization=True
            )
            print("索引加载成功")
            return True
        except Exception as e:
            print(f"加载索引时出错：{e}")
            return False

    def query(self, question: str, k: int = 3) -> dict:
        """查询数据库"""
        if not self.vectorstore:
            return {"error": "知识库未初始化"}

        # 1.检索相关文档
        retriever = self.vectorstore.as_retriever(
            search_type="similarity",
            search_kwargs={"k": k}
        )

        docs = retriever.invoke(question)

        # 2.构建提示词
        prompt = ChatPromptTemplate.from_template(
            """

            你是企业知识库问答助手。

            请给予以下文档回答问题

            文档片段：
            {context}

            用户问题：
            {question}

            回答要求：
            1.仅基于提供的文档内容回答，不要编造信息
            2.如果上下文没有相关信息，明确告诉用户
            3.回答要准确、完整、易懂
            4.如果答案来自多个文档片段，请综合回答

            答案：
            """
        )

        # 3.格式化文档
        def format_docs(docs):
            return "\n\n---\n\n".join([
                f"【文档 {i+1}】\n来源：{doc.metadata.get('source', '未知')}\n内容：{doc.page_content}"
                for i, doc in enumerate(docs)
            ])

        # 4.构建RAG Chain
        rag_chain = (
            {"context": lambda _: format_docs(docs), "question": RunnablePassthrough()}
            | prompt
            | self.model
            | StrOutputParser()
        )

        # 5.生成答案
        answer = rag_chain.invoke(question)

        # 6.记录查询
        self.query_log.append({
            "question": question,
            "answer": answer,
            "sources": [doc.metadata.get('source', '未知') for doc in docs],
            "timestamp": datetime.now().isoformat()
        })

        return {
            "question": question,
            "answer": answer,
            "sources": docs,
            "source_count": len(docs),
        }

    def export_logs(self, filename: str = "query_log.json"):
        """导出查询日志"""
        with open(filename, "w", encoding="utf-8") as f:
            json.dump(self.query_log, f, ensure_ascii=False, indent=2)
        print(f"查询日志已保存至 {filename}")

