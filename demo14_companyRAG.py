def main():
    """主程序"""
    print("="*80)
    print("企业知识库问答系统（Langchain 1.0）")
    print(f"当前时间：{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print("="*80)

    kb = KnowledgeBase()

    # 检查是否有已存在的索引
    if os.path.exists(kb.index_directory):
        print("\n 发现已有的索引")
        answer = input("是否使用已有索引？(y/n) ：").strip().lower()
        if answer == "y":
            if not kb.load_index():
                print("索引加载失败，请重新创建索引")
                create_sample_docs()
                kb.build_index()
        else:
            create_sample_docs()
            kb.build_index()
    else:
        print("\n 未发现已存在的索引，开始创建索引")
        create_sample_docs()
        if not kb.build_index():
            print("索引创建失败，程序退出")
            return

    # 示例查询
    print("\n" + "="*80)
    print("示例查询：")
    print("=" * 80)

    test_questions = [
        "公司简介",
        "团队介绍",
        "技术优势",
        "核心功能",
        "适用场景",
        "接入方式",
        "公司主要产品有哪些？"
    ]

    for question in test_questions:
        print(f"\n问题：{question}")
        result = kb.query(question)

        print(f"{result['question']} -> {result['answer']}")
        print(
            "参考文档："
            + ", ".join(doc.metadata.get("source", "未知") for doc in result["sources"])
        )
        print("=" * 80)

    # 交互模式
    print("\n" + "="*80)
    print("交互模式（输入quit退出，输入export导出日志）")
    print("=" * 80)

    while True:
        question = input("\n请输入问题：").strip()

        if question.lower() == 'quit':
            kb.export_logs()
            print("再见！")
            break

        if question.lower() == 'export':
            kb.export_logs()
            continue

        if not question:
            continue

        result = kb.query(question)

        print(f"\n 答案：\n {result['answer']}")
        print(f"参考来源：")
        for i, doc in enumerate(result['sources'], 1):
            print(f"    {i}. {doc['source']}")
            print(f"      内容片段：{doc.page_content[:100]}")

if __name__ == "__main__":
    main()
